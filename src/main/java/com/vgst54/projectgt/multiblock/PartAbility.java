package com.vgst54.projectgt.multiblock;

/** Способность люка: что он даёт мультиблоку. Паттерн указывает, какие способности допустимы на клетке. */
public enum PartAbility {
    /** Шина ввода предметов парового мультиблока (4 слота). */
    STEAM_IMPORT_ITEMS,
    /** Шина вывода предметов парового мультиблока (4 слота). */
    STEAM_EXPORT_ITEMS,
    /** Паровой люк: бак пара, из которого мультиблок берёт энергию. */
    STEAM
}
